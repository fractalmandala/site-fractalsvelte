// Generates src/lib/fractalsvelte-ui/loaders.ts: one lazy loader per
// fractalsvelte-ui component, so the variants gallery can mount the real
// published component without pulling all 124 into one chunk.
//
// Run with `pnpm docs:loaders`. Re-run after `pnpm docs:copy` adds components.
import fs from 'node:fs';
import path from 'node:path';

const ROOT = process.cwd();
const kebab = (name: string) => name.replace(/([a-z])([A-Z0-9])/g, '$1-$2').toLowerCase();

const manifestPath = path.join(ROOT, 'src/lib/generated/components/fractalsvelte-ui.json');
const manifest = JSON.parse(fs.readFileSync(manifestPath, 'utf8')) as {
	components: { name: string; file: string }[];
};

const rows = manifest.components.map((c) => {
	const slug = kebab(c.name);
	// manifest file is package-relative (src/lib/...) — dist mirrors it without the prefix
	const rel = String(c.file).replace(/^src\/lib\//, '');
	return `\t'${slug}': () => import('@fractaldesign/fractalsvelte-ui/${rel}'),`;
});

const out = `// AUTO-GENERATED by scripts/gen-component-loaders.ts — do not edit by hand.
import type { Component } from 'svelte';

export type ComponentLoader = () => Promise<{ default: Component }>;

/** Lazy loader for every published fractalsvelte-ui component, keyed by URL slug. */
export const componentLoaders: Record<string, ComponentLoader> = {
${rows.join('\n')}
};
`;

const outPath = path.join(ROOT, 'src/lib/fractalsvelte-ui/loaders.ts');
fs.writeFileSync(outPath, out);
console.log(`[docs:loaders] ${rows.length} loaders -> ${path.relative(ROOT, outPath)}`);
